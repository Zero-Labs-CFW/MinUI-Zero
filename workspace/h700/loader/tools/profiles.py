#!/usr/bin/env python3
"""Generate the compiled allowlist from tracked, reviewed transcript identities."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
BOARDS = {1: 'plus', 2: 'h', 3: 'pro', 4: 'sp', 5: 'rg40xx-h', 6: 'rg40xx-v',
          7: 'rgcubexx-h', 8: 'rg28xx-h', 9: 'rg34xx-h', 10: 'rg34xx-sp', 11: 'rgsp', 12: '2024'}
PANEL_RULES = {'strap-pull': 1, 'strap-unchanged': 2, 'old': 3, 'boe': 4}
DISPLAY_KEYS = ('lcd_width', 'lcd_height', 'manager_width', 'manager_height',
                'frame_width', 'frame_height')


def policy(row):
    if 'display' not in row:
        if row['id'] not in (1, 2):
            raise ValueError('new profile needs explicit display contract')
        return (640, 480, 640, 480, 640, 480)
    display = row['display']
    if set(display) != set(DISPLAY_KEYS):
        raise ValueError('incomplete display contract')
    values = tuple(display[key] for key in DISPLAY_KEYS)
    if any(type(n) is not int or not 0 < n <= 4096 for n in values):
        raise ValueError('invalid display dimensions')
    return values


def load(path=ROOT / 'profiles.json'):
    data = json.loads(path.read_text())
    if type(data['version']) is not int or data['version'] not in (1, 2) or not data['profiles']:
        raise ValueError('unsupported/empty profile manifest')
    seen = set()
    hashes = set()
    for row in data['profiles']:
        ident = row['id']
        if type(ident) is not int or ident not in BOARDS or ident in seen:
            raise ValueError('duplicate/unsupported profile')
        seen.add(ident)
        if row['board'] != BOARDS[ident] or type(row['ram_mib']) is not int or row['ram_mib'] not in (1024, 2048):
            raise ValueError('unsupported board/RAM')
        if data['version'] == 1 and (ident not in (1, 2) or row['ram_mib'] != 1024 or row['panel_rule'] != 'strap-pull'):
            raise ValueError('legacy manifest cannot expand admission')
        if row['panel_rule'] not in PANEL_RULES or row['qualification'] not in ('development-only', 'host-only', 'source-backed'):
            raise ValueError('unreviewed panel rule/qualification')
        dims = policy(row)
        if data['version'] == 1 and dims != (640, 480, 640, 480, 640, 480):
            raise ValueError('legacy display contract change')
        if data['version'] == 2 and ('display' not in row or 'dram_types' not in row):
            raise ValueError('expanded manifest needs explicit hardware policy')
        types = row.get('dram_types', [7, 8])
        if not isinstance(types, list) or not types or any(type(n) is not int or n not in (7, 8) for n in types) or len(set(types)) != len(types):
            raise ValueError('unsupported DRAM types')
        if len(row['lengths']) != 8 or any(type(n) is not int or not 0 < n <= 33554432 for n in row['lengths']):
            raise ValueError('invalid transcript lengths')
        if not re.fullmatch('[0-9a-f]{64}', row['sha256']):
            raise ValueError('invalid transcript SHA256')
        variants = row.get('variants', [])
        names = set()
        for variant in variants:
            name = variant.get('name', '')
            if not re.fullmatch('[a-z0-9-]{1,64}', name) or name in names:
                raise ValueError('duplicate/invalid variant name')
            names.add(name)
            if not re.fullmatch('[0-9a-f]{64}', variant.get('boot_header_sha256', '')):
                raise ValueError('invalid variant header SHA256')
            if type(variant.get('ram_mib', row['ram_mib'])) is not int or variant.get('ram_mib', row['ram_mib']) not in (1024, 2048):
                raise ValueError('invalid variant RAM')
            if data['version'] == 1 and variant.get('ram_mib', row['ram_mib']) != row['ram_mib']:
                raise ValueError('legacy variant RAM change')
        for digest in [row['sha256']] + [v.get('sha256', '') for v in variants]:
            if not re.fullmatch('[0-9a-f]{64}', digest) or digest in hashes:
                raise ValueError('duplicate/invalid transcript SHA256')
            hashes.add(digest)
    aliases = data.get('artifact_aliases', {})
    if not isinstance(aliases, dict) or (aliases and
            (data['version'] != 2 or aliases != {'2024': 'plus'} or 1 not in seen or 12 in seen)):
        raise ValueError('unsupported artifact alias')
    return data['profiles']


def render(rows):
    lines = ['/* Generated by tools/profiles.py from profiles.json. NOT secure boot or hardware qualification. */',
             'static const struct {', '    unsigned int id, ram_mib, lengths[8];',
             '    uint8_t hash[32];', '} profiles[] = {']
    for row in rows:
        for variant in [row] + row.get('variants', []):
            digest = variant['sha256']
            lines.append('    { %d, %d, { %s }, {' % (row['id'], variant.get('ram_mib', row['ram_mib']), ', '.join(map(str, row['lengths']))))
            digest = bytes.fromhex(digest)
            for start in range(0, 32, 8):
                lines.append('        ' + ', '.join('0x%02x' % b for b in digest[start:start + 8]) + ',')
            lines.append('    } },')
    return '\n'.join(lines + ['};', ''])


def render_policy(rows):
    lines = ['/* Generated by tools/profiles.py. Admission requires the exact transcript. */',
             'static const struct zero_profile_policy zero_profile_policies[] = {']
    for row in rows:
        dims = ', '.join(map(str, policy(row)))
        types = sum(1 << n for n in row.get('dram_types', [7, 8]))
        ram = {row['ram_mib']} | {v.get('ram_mib', row['ram_mib']) for v in row.get('variants', [])}
        mask = sum(1 << (n // 1024 - 1) for n in ram)
        lines.append('    { %d, %d, %d, %d, { %s } },' %
                     (row['id'], PANEL_RULES[row['panel_rule']], types, mask, dims))
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = load()
    for name, expected in (('profiles.inc', render(rows)), ('profile_policy.inc', render_policy(rows))):
        output = ROOT / name
        if args.check:
            if output.read_text() != expected:
                raise SystemExit(name + ' is stale')
        else:
            output.write_text(expected)
