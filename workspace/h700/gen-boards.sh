#!/bin/sh
# gen-boards.sh <boards.txt> <boards.h>: the board table (workspace/h700/boards.txt) as C for platform.c.
# Run by the h700 makefile's early target, before anything compiles platform.c. Fails on a malformed row.
set -e
in=$1; out=$2
awk '
BEGIN { print "// GENERATED by workspace/h700/gen-boards.sh from workspace/h700/boards.txt: edit that, not this."
        print "typedef struct { const char* dev; int w, h, rot, rows, pad, lid, sleep, pwm3; const char* label; } H700Board;"
        print "static const H700Board h700_boards[] = {" }
/^[ \t]*(#|$)/ { next }
{
	if (NF < 11 || $3 !~ /^[0-9]+$/ || $4 !~ /^[0-9]+$/ || $5 !~ /^[0-9]+$/ || $6 !~ /^[0-9]+$/ || $7 !~ /^[0-9]+$/) {
		print "gen-boards: bad row " NR ": " $0 > "/dev/stderr"; bad = 1; exit 1
	}
	dev = $1; sub(/^rg35xx-/, "", dev)
	f = "," $9 ","
	label = $11; for (i = 12; i <= NF; i++) label = label " " $i
	printf "\t{ \"%s\", %d, %d, %d, %d, %d, %d, %d, %d, \"%s\" },\n", dev, $3, $4, $5, $6, $7,
		(index(f, ",lid,") > 0), (index(f, ",sleep,") > 0), (index(f, ",pwm3,") > 0), label
	n++
}
END { if (bad) exit 1; if (!n) { print "gen-boards: no boards" > "/dev/stderr"; exit 1 } print "};" }
' "$in" > "$out.tmp"
# replace only on a change: a rewrite would make boards.h newer than the binaries built from it, and the image
# build refuses a binary older than any source (build-h700-stripped.sh freshness gate)
if cmp -s "$out.tmp" "$out"; then rm -f "$out.tmp"; else mv -f "$out.tmp" "$out"; fi
